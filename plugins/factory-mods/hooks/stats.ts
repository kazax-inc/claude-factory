// Usage metrics summed from the model requests the engine reports at each `turn.step`, and the
// Markdown bodies of the stats files. Field-by-field documentation: ../docs/data.md.

import type { ModelUsage } from 'claude-code'

export const TOKEN_KEYS = ['input', 'output', 'cache_read', 'cache_write'] as const
type TokenKey = (typeof TOKEN_KEYS)[number]
export type Tokens = Record<TokenKey | 'total', number>
export type Context = { peak_tokens: number; window: number | null; peak_pct: number | null }
export type Metrics = {
  duration_ms: number
  requests: number
  tool_calls: number
  tokens: Tokens
  cache_hit_rate: number | null
  context: Context
  by_model: Record<string, { requests: number; tokens: Tokens }>
}

// Context window per model prefix; anything not listed is assumed to have 1M.
const CONTEXT_WINDOWS: Record<string, number> = {
  'claude-haiku-4-5': 200_000,
  'claude-sonnet-4-5': 200_000,
  'claude-opus-4-5': 200_000,
}
const DEFAULT_CONTEXT_WINDOW = 1_000_000

const contextWindow = (model: string) =>
  Object.entries(CONTEXT_WINDOWS).find(([prefix]) => model.startsWith(prefix))?.[1] ?? DEFAULT_CONTEXT_WINDOW

const zeroTokens = (): Tokens => ({ input: 0, output: 0, cache_read: 0, cache_write: 0, total: 0 })

export const newMetrics = (): Metrics => ({
  duration_ms: 0,
  requests: 0,
  tool_calls: 0,
  tokens: zeroTokens(),
  cache_hit_rate: null,
  context: { peak_tokens: 0, window: null, peak_pct: null },
  by_model: {},
})

/** Adds one model request. */
export function addRequest(m: Metrics, model: string, usage: ModelUsage, toolCalls: number): void {
  const t: Record<TokenKey, number> = {
    input: usage.input_tokens,
    output: usage.output_tokens,
    cache_read: usage.cache_read_input_tokens,
    cache_write: usage.cache_creation_input_tokens,
  }
  const bm = (m.by_model[model] ??= { requests: 0, tokens: zeroTokens() })
  for (const k of TOKEN_KEYS) {
    m.tokens[k] += t[k]
    bm.tokens[k] += t[k]
  }
  bm.requests++
  m.requests++
  m.tool_calls += toolCalls
  const prompt = t.input + t.cache_read + t.cache_write
  if (prompt > m.context.peak_tokens) m.context = { peak_tokens: prompt, window: contextWindow(model), peak_pct: null }
  finalize(m)
}

/** Adds the metrics of a run (or of a stats file read back) into `acc`. */
export function merge(acc: Metrics, m: Partial<Metrics>): Metrics {
  acc.duration_ms += num(m.duration_ms)
  acc.requests += num(m.requests)
  acc.tool_calls += num(m.tool_calls)
  for (const k of TOKEN_KEYS) acc.tokens[k] += num(m.tokens?.[k])
  if (num(m.context?.peak_tokens) > acc.context.peak_tokens) acc.context = { ...(m.context as Context) }
  for (const [model, bm] of Object.entries(m.by_model ?? {})) {
    const a = (acc.by_model[model] ??= { requests: 0, tokens: zeroTokens() })
    a.requests += num(bm?.requests)
    for (const k of TOKEN_KEYS) a.tokens[k] += num(bm?.tokens?.[k])
  }
  return finalize(acc)
}

export function finalize(m: Metrics): Metrics {
  for (const bucket of [m, ...Object.values(m.by_model)])
    bucket.tokens.total = TOKEN_KEYS.reduce((sum, k) => sum + bucket.tokens[k], 0)
  const prompt = m.tokens.input + m.tokens.cache_read + m.tokens.cache_write
  m.cache_hit_rate = prompt ? round(m.tokens.cache_read / prompt) : null
  m.context.peak_pct = m.context.window ? round(m.context.peak_tokens / m.context.window) : null
  return m
}

/** The metrics fields of a stats file's frontmatter. */
export function metricsOf(data: Record<string, unknown>): Metrics {
  return merge(newMetrics(), data as Partial<Metrics>)
}

const num = (v: unknown) => (typeof v === 'number' && Number.isFinite(v) ? v : 0)
const round = (x: number) => Math.round(x * 10_000) / 10_000

export const isoTime = (ms: number) => new Date(ms).toISOString().replace(/\.\d{3}Z$/, 'Z')

export function msBetween(a: string | null | undefined, b: string | null | undefined): number | null {
  const ta = a ? Date.parse(a) : NaN
  const tb = b ? Date.parse(b) : NaN
  return Number.isNaN(ta) || Number.isNaN(tb) ? null : tb - ta
}

export function fmtMs(ms: number | null | undefined): string {
  if (ms == null) return '—'
  const s = Math.floor(ms / 1000)
  if (s >= 3600) return `${Math.floor(s / 3600)}h ${Math.floor((s % 3600) / 60)}m`
  return s >= 60 ? `${Math.floor(s / 60)}m ${s % 60}s` : `${s}s`
}

export function fmtNum(n: number | null | undefined): string {
  const v = n ?? 0
  return v >= 1e6 ? `${(v / 1e6).toFixed(2)}M` : v >= 1e3 ? `${(v / 1e3).toFixed(1)}k` : String(v)
}

export const fmtPct = (x: number | null | undefined) => (x == null ? '—' : `${(x * 100).toFixed(1)}%`)

/** A generated stats file's body: a title, a note, then one table row of metrics. */
export function statsBody(title: string, m: Metrics, timeLabel: string, timeMs: number | null, extra = ''): string {
  return (
    `# ${title}\n\n` +
    'Generated by the factory plugin from the requests Claude Code reported. Do not edit; ' +
    'programs read the frontmatter.\n\n' +
    `| ${timeLabel} | requests | tool calls | tokens | cache hit | peak context |\n` +
    '|---|---|---|---|---|---|\n' +
    `| ${fmtMs(timeMs)} | ${m.requests} | ${m.tool_calls} | ${fmtNum(m.tokens.total)} | ${fmtPct(m.cache_hit_rate)} ` +
    `| ${fmtNum(m.context.peak_tokens)} (${fmtPct(m.context.peak_pct)}) |\n` +
    extra
  )
}
